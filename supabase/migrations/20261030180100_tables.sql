-- Tracks -------------------------------------------------------------------

create table public.tracks (
  id uuid primary key default gen_random_uuid(),
  -- Generated by the insert trigger: title slug plus a random suffix.
  slug text not null default '' unique
    check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' and char_length(slug) <= 80),
  owner_id uuid not null references public.profiles (id) on delete cascade,
  title text not null check (char_length(btrim(title)) between 1 and 100),
  description text not null default '' check (char_length(description) <= 2000),
  genre_id smallint not null references public.genres (id),
  -- Each tag is validated by the tracks triggers (lowercase, 1 to 24 chars).
  tags text[] not null default '{}' check (cardinality(tags) <= 5),
  feedback_wants public.feedback_category[] not null default '{}',
  level public.track_level,
  duration_ms integer not null check (duration_ms between 1000 and 900000),
  -- Object keys are `<owner_id>/<random uuid>.mp3|json`, never user input.
  audio_key text not null unique,
  peaks_key text not null unique,
  waveform_color text check (waveform_color ~ '^#[0-9a-f]{6}$'),
  status public.track_status not null default 'live',
  play_count integer not null default 0 check (play_count >= 0),
  comment_count integer not null default 0 check (comment_count >= 0),
  reaction_counts jsonb not null default '{}'::jsonb,
  published_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  constraint tracks_audio_key_format check (
    audio_key ~ '^[0-9a-f-]{36}/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.mp3$'
    and split_part(audio_key, '/', 1) = owner_id::text
  ),
  constraint tracks_peaks_key_format check (
    peaks_key ~ '^[0-9a-f-]{36}/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.json$'
    and split_part(peaks_key, '/', 1) = owner_id::text
  )
);

create index tracks_owner_id_idx on public.tracks (owner_id, created_at desc);
create index tracks_genre_id_idx on public.tracks (genre_id);
create index tracks_live_published_idx on public.tracks (published_at desc)
  where status = 'live';
create index tracks_needs_ears_idx on public.tracks (published_at desc)
  where status = 'live' and comment_count <= 1;

-- Upload IPs are kept apart from tracks so they can never be selected through
-- the public tracks table. Deleted after 30 days by pg_cron.
create table public.track_upload_ips (
  track_id uuid primary key references public.tracks (id) on delete cascade,
  ip inet not null,
  created_at timestamptz not null default now()
);

create index track_upload_ips_created_at_idx on public.track_upload_ips (created_at);

-- Comments -----------------------------------------------------------------

create table public.comments (
  id uuid primary key default gen_random_uuid(),
  track_id uuid not null references public.tracks (id) on delete cascade,
  author_id uuid not null default auth.uid()
    references public.profiles (id) on delete cascade,
  -- One level of replies. A deleted parent turns its replies into top level
  -- comments instead of deleting other people's text.
  parent_id uuid references public.comments (id) on delete set null,
  -- null means the comment is about the whole track.
  time_ms integer check (time_ms >= 0),
  category public.feedback_category not null default 'vibe',
  body text not null check (char_length(btrim(body)) between 1 and 2000),
  is_helpful boolean not null default false,
  helpful_at timestamptz,
  resolved_at timestamptz,
  status public.comment_status not null default 'live',
  created_at timestamptz not null default now(),
  edited_at timestamptz
);

create index comments_track_id_idx on public.comments (track_id, time_ms);
create index comments_author_id_idx on public.comments (author_id, created_at desc);
create index comments_parent_id_idx on public.comments (parent_id)
  where parent_id is not null;
create index comments_helpful_idx on public.comments (author_id, helpful_at)
  where is_helpful;
create index comments_created_at_idx on public.comments (created_at)
  where status = 'live';

-- Reactions ----------------------------------------------------------------

create table public.reactions (
  track_id uuid not null references public.tracks (id) on delete cascade,
  user_id uuid not null default auth.uid()
    references public.profiles (id) on delete cascade,
  kind public.reaction_kind not null,
  created_at timestamptz not null default now(),
  primary key (track_id, user_id, kind)
);

create index reactions_user_id_idx on public.reactions (user_id);
create index reactions_created_at_idx on public.reactions (created_at);

-- Reports ------------------------------------------------------------------
--
-- The plan sketches a polymorphic target_id. We use one foreign key per
-- target type instead, so reports can never point at a missing row and are
-- cleaned up with their target.

create table public.reports (
  id uuid primary key default gen_random_uuid(),
  reporter_id uuid not null default auth.uid()
    references public.profiles (id) on delete cascade,
  target_type public.report_target not null,
  track_id uuid references public.tracks (id) on delete cascade,
  comment_id uuid references public.comments (id) on delete cascade,
  reason public.report_reason not null,
  details text not null default '' check (char_length(details) <= 1000),
  status public.report_status not null default 'open',
  resolved_by uuid references public.profiles (id) on delete set null,
  resolved_at timestamptz,
  created_at timestamptz not null default now(),
  constraint reports_target_matches check (
    (target_type = 'track' and track_id is not null and comment_id is null)
    or (target_type = 'comment' and comment_id is not null and track_id is null)
  ),
  constraint reports_one_per_track unique (reporter_id, track_id),
  constraint reports_one_per_comment unique (reporter_id, comment_id)
);

create index reports_track_id_idx on public.reports (track_id) where track_id is not null;
create index reports_comment_id_idx on public.reports (comment_id) where comment_id is not null;
create index reports_open_idx on public.reports (created_at) where status = 'open';
create index reports_resolved_by_idx on public.reports (resolved_by) where resolved_by is not null;

-- Notifications ------------------------------------------------------------

create table public.notifications (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles (id) on delete cascade,
  kind public.notification_kind not null,
  actor_id uuid references public.profiles (id) on delete cascade,
  track_id uuid references public.tracks (id) on delete cascade,
  comment_id uuid references public.comments (id) on delete cascade,
  read_at timestamptz,
  created_at timestamptz not null default now()
);

create index notifications_user_id_idx on public.notifications (user_id, created_at desc);
create index notifications_actor_id_idx on public.notifications (actor_id);
create index notifications_track_id_idx on public.notifications (track_id);
create index notifications_comment_id_idx on public.notifications (comment_id);

-- Rate limit ledger --------------------------------------------------------
--
-- Rate limits count events here instead of rows in the content tables, so
-- deleting and re-posting does not reset the window. Purged by pg_cron.

create table private.rate_limit_events (
  id bigint generated always as identity primary key,
  user_id uuid not null references public.profiles (id) on delete cascade,
  action text not null check (action in ('track', 'comment', 'report')),
  created_at timestamptz not null default now()
);

create index rate_limit_events_lookup_idx
  on private.rate_limit_events (user_id, action, created_at desc);
create index rate_limit_events_created_at_idx on private.rate_limit_events (created_at);
