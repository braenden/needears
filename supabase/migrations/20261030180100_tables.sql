-- Tables, constraints and indexes for the whole v1 data model.
-- Triggers live in the next migration, RLS and grants in the one after.

-- Profiles -----------------------------------------------------------------

create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  handle text not null unique
    constraint profiles_handle_format check (handle ~ '^[a-z0-9_]{3,20}$'),
  display_name text not null
    check (char_length(btrim(display_name)) between 1 and 50),
  avatar_url text
    check (avatar_url ~ '^https://' and char_length(avatar_url) <= 500),
  bio text not null default '' check (char_length(bio) <= 300),
  role public.user_role not null default 'user',
  -- Number of live comments by this user marked Helpful. Kept by triggers.
  reputation integer not null default 0 check (reputation >= 0),
  -- Shadow ban: new content from a banned user is hidden from everyone else.
  banned_at timestamptz,
  created_at timestamptz not null default now()
);

-- Genres -------------------------------------------------------------------

create table public.genres (
