import { isIP } from "node:net";
import { z } from "zod";
import { requireUser } from "@/lib/api/auth";
import { BodyError, databaseError, jsonError, readJson } from "@/lib/api/http";
import { createAdminClient } from "@/lib/supabase/admin";
import { MAX_DURATION_MS, MIN_DURATION_MS } from "@/config/upload";
import { isAllowedLinkUrl } from "@/config/profile";
import { LOUDNESS_MAX, LOUDNESS_MIN } from "@/config/versions";
import { objectKeys } from "@/lib/upload/keys";
import { verifyUpload } from "@/lib/upload/verify";
import { Constants } from "@/types/database";

const enums = Constants.public.Enums;

const bodySchema = z
  .object({
    // Keys are lowercase; an uppercase id must not end in a 500.
    objectId: z.uuid().transform((id) => id.toLowerCase()),
    title: z.string().trim().min(1).max(100),
    description: z.string().trim().max(2000).default(""),
    genre: z.string().regex(/^[a-z0-9]+(-[a-z0-9]+)*$/),
    tags: z.array(z.string().max(24)).max(5).default([]),
    feedbackWants: z.array(z.enum(enums.feedback_category)).max(5).default([]),
    level: z.enum(enums.track_level).nullable().default(null),
    durationMs: z.number().int().min(MIN_DURATION_MS).max(MAX_DURATION_MS),
    // Integrated loudness in LUFS, measured while decoding. Optional.
    loudness: z
      .number()
      .min(LOUDNESS_MIN)
      .max(LOUDNESS_MAX)
      .nullable()
      .default(null),
    // A link to a track the uploader is aiming for (profile link hosts).
    referenceUrl: z
      .string()
      .trim()
      .refine(isAllowedLinkUrl)
      .nullable()
      .default(null),
    waveformColor: z
      .string()
      .regex(/^#[0-9a-f]{6}$/)
      .nullable()
      .default(null),
    // "This is my own work, not generated by AI." Required.
    ownWork: z.literal(true),
  })
  .strict();

// The client IP as seen by Vercel. Stored for 30 days for takedown tracing.
function clientIp(request: Request): string | null {
  const forwarded = request.headers
    .get("x-forwarded-for")
    ?.split(",")[0]
    ?.trim();
  const ip = forwarded || request.headers.get("x-real-ip")?.trim();
  return ip && isIP(ip) ? ip : null;
}

// Step 2 of an upload. Verifies the objects the browser uploaded with the
// URLs from /api/upload/sign and creates the track. Users cannot insert
// tracks directly (no grant), so this is the only way in. Rate limits and
// the storage ownership check also run in the database trigger.
export async function POST(request: Request) {
  const auth = await requireUser(request);
  if (auth instanceof Response) return auth;

  let body;
  try {
    body = bodySchema.safeParse(await readJson(request));
  } catch (error) {
    if (error instanceof BodyError)
      return jsonError(400, "invalid_body", error.message);
    throw error;
  }
  if (!body.success) {
    return jsonError(
      400,
      "invalid_track",
      "Check the title, genre and the other fields.",
    );
  }
  const input = body.data;

  const keys = objectKeys(auth.user.id, input.objectId);
  const admin = createAdminClient();

  const genre = await admin
    .from("genres")
    .select("id")
    .eq("slug", input.genre)
    .maybeSingle();
  if (genre.error) return databaseError(genre.error);
  if (!genre.data)
    return jsonError(400, "unknown_genre", "Pick one of the listed genres.");

  const verified = await verifyUpload(admin, keys, input.durationMs);
  if (!verified.ok) {
    await removeUnusedObjects(admin, keys);
    return jsonError(422, verified.code, verified.message);
  }

  const inserted = await admin
    .from("tracks")
    .insert({
      owner_id: auth.user.id,
      title: input.title,
      description: input.description,
      genre_id: genre.data.id,
      tags: input.tags,
      feedback_wants: input.feedbackWants,
      level: input.level,
      duration_ms: input.durationMs,
      audio_key: keys.audioKey,
      peaks_key: keys.peaksKey,
      waveform_color: input.waveformColor,
      reference_url: input.referenceUrl,
    })
    .select("id, slug")
    .single();

  if (inserted.error) {
    if (inserted.error.code !== "23505") await removeUnusedObjects(admin, keys);
    return databaseError(inserted.error);
  }

  // Version 1 was created with the track; it carries the loudness.
  if (input.loudness !== null) {
    const loud = await admin
      .from("track_versions")
      .update({ loudness: Math.round(input.loudness * 100) / 100 })
      .eq("track_id", inserted.data.id)
      .eq("version_no", 1);
    if (loud.error) console.error("Could not store loudness", loud.error.code);
  }

  const ip = clientIp(request);
  if (ip) {
    const stored = await admin
      .from("track_upload_ips")
      .insert({ track_id: inserted.data.id, ip });
    if (stored.error)
      console.error("Could not store upload IP", stored.error.code);
  }

  return Response.json(inserted.data, {
    status: 201,
    headers: { "Cache-Control": "no-store" },
  });
}

// Removes rejected uploads, unless a track already uses them (a repeated
// request for an upload that already succeeded).
async function removeUnusedObjects(
  admin: ReturnType<typeof createAdminClient>,
  keys: { audioKey: string; peaksKey: string },
) {
  // Version 1 and every later version are in track_versions.
  const used = await admin
    .from("track_versions")
    .select("id", { count: "exact", head: true })
    .eq("audio_key", keys.audioKey);
  if (used.error || (used.count ?? 0) > 0) return;
  await Promise.all([
    admin.storage.from("audio").remove([keys.audioKey]),
    admin.storage.from("peaks").remove([keys.peaksKey]),
  ]);
}
