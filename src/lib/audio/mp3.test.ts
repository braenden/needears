import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { inspectMp3 } from "./mp3";

// MPEG 1 layer III, 128 kbps, 44.1 kHz, stereo, no padding: 417 byte frames.
function cbrFile(frames: number, prefix: number[] = []): Uint8Array {
  const frame = new Uint8Array(417);
  frame.set([0xff, 0xfb, 0x90, 0x00]);
  const out = new Uint8Array(prefix.length + frames * 417);
  out.set(prefix);
  for (let i = 0; i < frames; i++) out.set(frame, prefix.length + i * 417);
  return out;
}

describe("inspectMp3", () => {
  it("estimates the duration of a CBR file", () => {
    // 100 frames of 1152 samples at 44.1 kHz is 2.61 s.
    const file = cbrFile(100);
    const info = inspectMp3(file, file.length);
    expect(info).toMatchObject({
      bitrateKbps: 128,
      sampleRate: 44100,
      vbr: false,
    });
    expect(info!.durationMs).toBeGreaterThan(2550);
    expect(info!.durationMs).toBeLessThan(2670);
  });

  it("skips an ID3v2 tag", () => {
    const tag = [
      0x49,
      0x44,
      0x33,
      4,
      0,
      0,
      0,
      0,
      0,
      20,
      ...new Array(20).fill(0),
    ];
    const file = cbrFile(10, tag);
    expect(inspectMp3(file, file.length)).not.toBeNull();
  });

  it("reads the frame count from a Xing header", () => {
    const file = cbrFile(10);
    // Side info for MPEG 1 stereo is 32 bytes, so the tag starts at 36.
    file.set([...Buffer.from("Xing"), 0, 0, 0, 1, 0, 0, 0x27, 0x10], 36);
    const info = inspectMp3(file, 10_000_000);
    // 10000 frames * 1152 / 44100 = 261.2 s
    expect(info).toMatchObject({ vbr: true, durationMs: 261224 });
  });

  it("rejects a Xing frame count that does not fit the file size", () => {
    // 1000 frames is 26 s, but 10 MB in 26 s would be about 3000 kbps: the
    // count was faked and the rest of the file is not audio.
    const file = cbrFile(10);
    file.set([...Buffer.from("Xing"), 0, 0, 0, 1, 0, 0, 0x03, 0xe8], 36);
    expect(inspectMp3(file, 10_000_000)).toBeNull();
  });

  it("measures the seed files generated by ffmpeg", () => {
    const file = readFileSync(
      new URL(
        "../../../supabase/seed-storage/audio/a0000000-0000-4000-8000-000000000001/c0000000-0000-4000-8000-000000000001.mp3",
        import.meta.url,
      ),
    );
    const info = inspectMp3(
      new Uint8Array(file).subarray(0, 65536),
      file.length,
    );
    expect(info).toMatchObject({ bitrateKbps: 32, sampleRate: 22050 });
    expect(Math.abs(info!.durationMs - 24000)).toBeLessThan(500);
  });

  it.each([
    [
      "a WAV file",
      [...Buffer.from("RIFF"), 0, 0, 0, 0, ...Buffer.from("WAVEfmt ")],
    ],
    [
      "an HTML file",
      [...Buffer.from("<html><script>alert(1)</script></html>")],
    ],
    ["a lone sync word", [0xff, 0xfb, 0x90, 0x00, 1, 2, 3, 4]],
    ["an empty file", []],
  ])("rejects %s", (_name, bytes) => {
    const file = new Uint8Array(bytes);
    expect(inspectMp3(file, file.length)).toBeNull();
  });
});
