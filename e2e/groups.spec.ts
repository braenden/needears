import { expect, type Page, test } from "@playwright/test";
import { pageIn, signInWithMagicLink, testWav, trackMenu } from "./helpers";

// A class from start to finish: a teacher makes a group, a student finds it
// by searching, asks to join and is let in, then uploads in the group. Only
// members hear it: someone outside finds nothing, from any way in. The
// teacher deletes the track, and then the group.
const stamp = Date.now().toString(36);
const teacher = { handle: `t_${stamp}`, email: `t_${stamp}@example.com` };
const student = { handle: `s_${stamp}`, email: `s_${stamp}@example.com` };
const groupName = `Mix class ${stamp}`;
const title = `Class demo ${stamp}`;
const teacherTitle = `Teacher demo ${stamp}`;

/** Uploads a short wav from the group's page, as the person on `page`. */
async function uploadInGroup(page: Page, groupPath: string, name: string) {
  await page.goto(groupPath);
  await pageIn(page);
  await page.getByRole("link", { name: "Upload to group" }).click();
  await page.locator('input[type="file"]').setInputFiles({
    name: "demo.wav",
    mimeType: "audio/wav",
    buffer: testWav(),
  });
  await page.getByLabel("Title").fill(name);
  await page.getByLabel("Genre").selectOption({ index: 1 });
  await page.getByRole("button", { name: "Continue" }).click();
  await page
    .getByRole("checkbox", {
      name: "Made by me (samples are fine), not generated by AI.",
    })
    .check();
  await page.getByRole("button", { name: "Publish to group" }).click();
  await expect(page).toHaveURL(new RegExp(`${groupPath}$`), {
    timeout: 60_000,
  });
  const link = page.getByRole("link", { name }).first();
  await expect(link).toBeVisible();
  return (await link.getAttribute("href")) ?? "";
}

async function signUp(page: Page, who: { handle: string; email: string }) {
  await signInWithMagicLink(page, who.email, "/groups");
  await expect(page).toHaveURL(/\/welcome/);
  await page.getByLabel("Username").fill(who.handle);
  await page.getByRole("button", { name: "Continue" }).click();
  await expect(page).toHaveURL(/\/groups$/);
}

test("a class: make a group, ask to join, let in, upload, delete", async ({
  browser,
}) => {
  test.slow();
  const teacherPage = await (await browser.newContext()).newPage();
  const studentPage = await (await browser.newContext()).newPage();
  const outsider = await (await browser.newContext()).newPage();
  let groupPath = "";
  let trackPath = "";

  await test.step("the teacher makes the group the same day", async () => {
    await signUp(teacherPage, teacher);
    await teacherPage.getByRole("link", { name: "New group" }).click();
    await teacherPage.getByLabel("Name", { exact: true }).fill(groupName);
    await teacherPage.getByRole("button", { name: "Create group" }).click();
    await expect(teacherPage).toHaveURL(/\/g\/[a-z0-9-]+$/);
    groupPath = new URL(teacherPage.url()).pathname;
    await expect(
      teacherPage.getByRole("heading", { name: groupName, level: 1 }),
    ).toBeVisible();
    await expect(teacherPage.getByText("No tracks yet.")).toBeVisible();
  });

  await test.step("a student finds it by name and asks to join", async () => {
    await signUp(studentPage, student);
    await studentPage.goto(`/search?q=${encodeURIComponent(groupName)}`);
    await pageIn(studentPage);
    await studentPage
      .getByRole("link", { name: new RegExp(groupName) })
      .click();
    await expect(studentPage).toHaveURL(new RegExp(`${groupPath}$`));
    await expect(
      studentPage.getByText("Only members see what's in this group."),
    ).toBeVisible();
    await studentPage.getByRole("button", { name: "Ask to join" }).click();
    await expect(studentPage.getByText(/You asked to join\./)).toBeVisible();
  });

  await test.step("the teacher lets the student in", async () => {
    await teacherPage.reload();
    await pageIn(teacherPage);
    const asks = teacherPage.getByRole("region", { name: /Asked to join/ });
    await asks.getByRole("button", { name: /^Let in / }).click();
    await expect(teacherPage.getByText(/ is in\.$/)).toBeVisible();
    await expect(
      teacherPage.getByRole("region", { name: /^Members/ }),
    ).toContainText("2");
  });

  await test.step("the student is told, and uploads in the group", async () => {
    await studentPage.goto("/notifications");
    await pageIn(studentPage);
    await expect(
      studentPage.getByText(new RegExp(`let you into ${groupName}`)),
    ).toBeVisible();
    await studentPage.goto(groupPath);
    await pageIn(studentPage);
    await studentPage.getByRole("link", { name: "Upload to group" }).click();
    await expect(studentPage.getByText(`In ${groupName}`)).toBeVisible();
    await studentPage.locator('input[type="file"]').setInputFiles({
      name: "class-demo.wav",
      mimeType: "audio/wav",
      buffer: testWav(),
    });
    await studentPage.getByLabel("Title").fill(title);
    await studentPage.getByLabel("Genre").selectOption({ index: 1 });
    await studentPage.getByRole("button", { name: "Continue" }).click();
    await expect(
      studentPage.getByText(`Only members of ${groupName} can hear this.`),
    ).toBeVisible();
    await studentPage
      .getByRole("checkbox", {
        name: "Made by me (samples are fine), not generated by AI.",
      })
      .check();
    await studentPage.getByRole("button", { name: "Publish to group" }).click();
    await expect(studentPage).toHaveURL(new RegExp(`${groupPath}$`), {
      timeout: 60_000,
    });
    const link = studentPage.getByRole("link", { name: title }).first();
    await expect(link).toBeVisible();
    trackPath = (await link.getAttribute("href")) ?? "";
    expect(trackPath).toMatch(/^\/t\//);
  });

  await test.step("someone outside finds nothing of it", async () => {
    const response = await outsider.goto(trackPath);
    expect(response?.status()).toBe(404);
    await expect(
      outsider.getByRole("heading", { name: "Only members can hear this." }),
    ).toBeVisible();
    await expect(outsider.getByText(title)).toHaveCount(0);
    expect(await outsider.title()).not.toContain(title);
    await outsider.goto("/feed?tab=latest");
    await pageIn(outsider);
    await expect(outsider.getByText(title)).toHaveCount(0);
    await outsider.goto(`/search?q=${encodeURIComponent(title)}`);
    await pageIn(outsider);
    await expect(outsider.getByRole("link", { name: title })).toHaveCount(0);
    // The group itself is only its card.
    await outsider.goto(groupPath);
    await expect(
      outsider.getByRole("link", { name: "Sign in to ask to join" }),
    ).toBeVisible();
    await expect(outsider.getByText(title)).toHaveCount(0);
  });

  await test.step("the teacher deletes their own track, also when it is reported", async () => {
    const teacherTrack = await uploadInGroup(
      teacherPage,
      groupPath,
      teacherTitle,
    );
    await studentPage.goto(teacherTrack);
    await pageIn(studentPage);
    await trackMenu(studentPage, "Report track");
    const report = studentPage.getByRole("dialog");
    await report.getByRole("radio", { name: "Spam or ads" }).check();
    await report.getByRole("button", { name: "Send report" }).click();
    await expect(report.getByText("Report sent")).toBeVisible();

    await teacherPage.goto(teacherTrack);
    await pageIn(teacherPage);
    await trackMenu(teacherPage, "Delete track");
    const dialog = teacherPage.getByRole("dialog", {
      name: "Delete this track?",
    });
    await dialog.getByRole("button", { name: "Delete track" }).click();
    await expect(teacherPage).toHaveURL(new RegExp(`${groupPath}$`));
    await expect(
      teacherPage.getByRole("link", { name: teacherTitle }),
    ).toHaveCount(0);
  });

  await test.step("the teacher deletes the track, then the group", async () => {
    await teacherPage.goto(groupPath);
    await pageIn(teacherPage);
    await teacherPage
      .getByRole("button", { name: `More for ${title}` })
      .first()
      .click();
    await teacherPage.getByRole("menuitem", { name: "Delete track" }).click();
    const dialog = teacherPage.getByRole("dialog", {
      name: `Delete ${title}?`,
    });
    await expect(dialog).toContainText("It's deleted for everyone, also for");
    await dialog.getByRole("button", { name: "Delete" }).click();
    await expect(teacherPage.getByRole("link", { name: title })).toHaveCount(0);

    await teacherPage.getByRole("button", { name: "Delete group" }).click();
    const confirm = teacherPage.getByRole("dialog", {
      name: `Delete ${groupName}?`,
    });
    const button = confirm.getByRole("button", { name: "Delete group" });
    await expect(button).toBeDisabled();
    await confirm.getByLabel(`Type ${groupName} to delete it.`).fill(groupName);
    await button.click();
    await expect(teacherPage).toHaveURL(/\/groups$/);
    await expect(
      teacherPage.getByText(`${groupName} is deleted.`),
    ).toBeVisible();
  });
});
