import { expect, test } from "@playwright/test";
import { signInWithMagicLink, testWav, trackMenu, pageIn } from "./helpers";

// The main flow, with two people:
// a new producer who signs up, uploads and later deletes the account, and the
// seed user Jonas, who leaves the comment. Owners cannot mark their own
// comments as Helpful, so the comment has to come from someone else.
const handle = `e2e_${Date.now().toString(36)}`;
const ownerEmail = `${handle}@example.com`;
const jonas = {
  email: "jonas@example.com",
  name: "Jonas Berg",
  handle: "jonas",
};
const title = `E2E rough mix ${handle}`;
const commentText = "The kick gets lost here, try a little more around 60 Hz.";

test("upload, comment at 0:05, Helpful, report and delete the account", async ({
  browser,
}) => {
  const owner = await (
    await browser.newContext({
      permissions: ["clipboard-read", "clipboard-write"],
    })
  ).newPage();
  const listener = await (await browser.newContext()).newPage();
  let trackPath = "";

  await test.step("a new producer signs up with a magic link", async () => {
    await signInWithMagicLink(owner, ownerEmail, "/upload");
    await expect(owner).toHaveURL(/\/welcome/);
    await owner.getByLabel("Username").fill(handle);
    await owner.getByRole("button", { name: "Continue" }).click();
    await expect(owner).toHaveURL(/\/upload$/);
  });

  await test.step("uploads a short wav", async () => {
    await owner.locator('input[type="file"]').setInputFiles({
      name: "rough-mix.wav",
      mimeType: "audio/wav",
      buffer: testWav(),
    });
    await owner.getByLabel("Title").fill(title);
    await owner.getByLabel("Genre").selectOption({ index: 1 });
    await owner.getByRole("button", { name: "Continue" }).click();
    await owner
      .getByRole("checkbox", {
        name: "Made by me (samples are fine), not generated by AI.",
      })
      .check();
    await owner.getByRole("button", { name: "Publish" }).click();
    const view = owner.getByRole("link", { name: "View track" });
    await expect(view).toBeVisible({ timeout: 60_000 });
    trackPath = (await view.getAttribute("href")) ?? "";
    expect(trackPath).toMatch(/^\/t\//);
    await owner.getByRole("button", { name: "Copy link" }).click();
    await expect(owner.getByText("Link copied.")).toBeVisible();
    expect(await owner.evaluate(() => navigator.clipboard.readText())).toBe(
      new URL(trackPath, owner.url()).href,
    );
  });

  await test.step("someone else comments at 0:05 and sees the marker", async () => {
    await signInWithMagicLink(listener, jonas.email, trackPath);
    await expect(listener).toHaveURL(trackPath);
    await expect(listener.getByRole("heading", { name: title })).toBeVisible();
    // One line until used; its time menu can pin another second.
    await listener.getByLabel("Comment", { exact: true }).click();
    await listener.getByRole("button", { name: /Comment at 0:00/ }).click();
    await listener.getByRole("menuitem", { name: "Change the time" }).click();
    const time = listener.getByLabel("at", { exact: true });
    await time.fill("0:05");
    await time.press("Enter");
    await expect(
      listener.getByRole("button", { name: /Comment at 0:05/ }),
    ).toBeVisible();
    await listener.getByLabel("Comment", { exact: true }).fill(commentText);
    await listener
      .getByRole("button", { name: "Comment", exact: true })
      .click();
    await expect(listener.getByText(commentText)).toBeVisible();
    // The comment says who wrote it: a link to the profile.
    await expect(
      listener
        .getByRole("list", { name: "Comments" })
        .getByRole("link", { name: jonas.name, exact: true })
        .first(),
    ).toHaveAttribute("href", `/u/${jonas.handle}`);
    await expect(
      listener.getByRole("button", {
        name: `Comment by ${jonas.name} at 0:05`,
      }),
    ).toBeVisible();
  });

  await test.step("listening to the whole short track counts one play", async () => {
    const counted = listener.waitForResponse(
      (r) => r.url().endsWith("/play") && r.request().method() === "POST",
      { timeout: 20_000 },
    );
    await listener.getByRole("button", { name: "Play", exact: true }).click();
    // The player sends it with keepalive, so the body cannot be read here;
    // the count on the page after a reload is the real check.
    expect((await counted).ok()).toBe(true);
    await listener.reload();
    await pageIn(listener);
    // The plays are in the track's details.
    await listener.getByRole("button", { name: "More for this track" }).click();
    await listener.getByRole("menuitem", { name: "Track details" }).click();
    await expect(
      listener.getByRole("dialog").getByText("1 play", { exact: true }),
    ).toBeVisible();
    await listener.keyboard.press("Escape");
  });

  await test.step("the producer marks it Helpful and reports it", async () => {
    await owner.goto(trackPath);
    await pageIn(owner);
    await expect(
      owner.getByRole("button", { name: `Comment by ${jonas.name} at 0:05` }),
    ).toBeVisible();
    // One tap beside Reply.
    const helpful = owner.getByRole("button", { name: "Helpful", exact: true });
    await helpful.click();
    await expect(helpful).toHaveAttribute("aria-pressed", "true");

    // The mark is stored, not just shown.
    await owner.reload();
    await expect(
      owner.getByRole("button", { name: "Helpful", exact: true }),
    ).toHaveAttribute("aria-pressed", "true");

    await owner
      .getByRole("button", {
        name: `More actions for the comment by ${jonas.name}`,
      })
      .click();
    await owner.getByRole("menuitem", { name: "Report comment" }).click();
    const dialog = owner.getByRole("dialog");
    await dialog.getByRole("radio", { name: "Spam or ads" }).check();
    await dialog.getByRole("button", { name: "Send report" }).click();
    await expect(dialog.getByText("Report sent")).toBeVisible();
    await dialog.getByRole("button", { name: "Close" }).first().click();
  });

  await test.step("the producer edits the details after publishing", async () => {
    await trackMenu(owner, "Edit details");
    const dialog = owner.getByRole("dialog");
    await dialog.getByLabel("Title").fill(`${title} v2`);
    await dialog.getByLabel(/Description/).fill("Second pass on the drums.");
    await dialog.getByRole("button", { name: "Save changes" }).click();
    await expect(dialog).toBeHidden();

    // Stored, and the link stays the same.
    await owner.goto(trackPath);
    await pageIn(owner);
    await expect(
      owner.getByRole("heading", { name: `${title} v2` }),
    ).toBeVisible();
    await expect(owner.getByText("Second pass on the drums.")).toBeVisible();
  });

  await test.step("the producer deletes the account", async () => {
    await owner.goto("/settings");
    await owner.getByRole("button", { name: "Delete my account" }).click();
    const dialog = owner.getByRole("dialog");
    await dialog.getByLabel(`Type ${handle} to confirm`).fill(handle);
    await dialog.getByRole("button", { name: "Delete everything" }).click();
    await expect(
      owner.getByText("Your account and everything you posted are deleted."),
    ).toBeVisible();

    // The track went with the account.
    const res = await listener.goto(trackPath);
    expect(res?.status()).toBe(404);
    await expect(
      listener.getByRole("heading", { name: "Page not found" }),
    ).toBeVisible();
  });
});
