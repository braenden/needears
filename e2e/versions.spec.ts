import { expect, test } from "@playwright/test";
import {
  largestStep,
  signInWithMagicLink,
  testWav,
  trackMenu,
  watchVolumeSteps,
} from "./helpers";

// A producer uploads a track and a second version with a note, switches
// between them, and leaves a comment on the first one, which stays there.
const handle = `e2v_${Date.now().toString(36)}`;
const note = `Louder kick, shorter intro ${handle}`;
const onFirst = `The intro on v1 drags a little ${handle}`;

test("new version, picker, A/B and comments per version", async ({ page }) => {
  let trackPath = "";
  await watchVolumeSteps(page);

  await test.step("a producer uploads a track", async () => {
    await signInWithMagicLink(page, `${handle}@example.com`, "/upload");
    await page.getByLabel("Username").fill(handle);
    await page.getByRole("button", { name: "Continue" }).click();
    await expect(page).toHaveURL(/\/upload$/);
    await page.locator('input[type="file"]').setInputFiles({
      name: "v1.wav",
      mimeType: "audio/wav",
      buffer: testWav(),
    });
    await page.getByLabel("Title").fill(`Versions ${handle}`);
    await page.getByLabel("Genre").selectOption({ index: 1 });
    await page.getByRole("button", { name: "Continue" }).click();
    await page
      .getByRole("checkbox", {
        name: "This is my own work, not generated by AI.",
      })
      .check();
    await page.getByRole("button", { name: "Publish" }).click();
    const view = page.getByRole("link", { name: "View track" });
    await expect(view).toBeVisible({ timeout: 60_000 });
    trackPath = (await view.getAttribute("href")) ?? "";
  });

  await test.step("uploads v2 with what changed", async () => {
    await page.goto(trackPath);
    await trackMenu(page, "Upload a new version");
    const dialog = page.getByRole("dialog");
    await dialog.locator('input[type="file"]').setInputFiles({
      name: "v2.wav",
      mimeType: "audio/wav",
      buffer: testWav(6),
    });
    await dialog.getByLabel(/What changed/).fill(note);
    await dialog.getByRole("button", { name: "Publish v2" }).click();
    await expect(dialog.getByText("v2 is live")).toBeVisible({
      timeout: 60_000,
    });
    await dialog.getByRole("button", { name: "Done" }).click();
    await expect(page.getByRole("radio", { name: /v2/ })).toBeChecked();
    await expect(page.getByText(note)).toBeVisible();
  });

  await test.step("switches versions and back with A/B", async () => {
    await page.getByRole("radio", { name: /v1/ }).click();
    await expect(page.getByRole("radio", { name: /v1/ })).toBeChecked();
    await page.getByRole("button", { name: /A\/B/ }).click();
    await expect(page.getByRole("radio", { name: /v2/ })).toBeChecked();
  });

  await test.step("switching while playing fades instead of cutting", async () => {
    await page.getByRole("radio", { name: /v2/ }).click();
    const play = page.getByRole("button", { name: "Play", exact: true });
    const pause = page.getByRole("button", { name: "Pause", exact: true });
    await play.click();
    await expect(pause).toBeVisible();
    await page.waitForTimeout(1000);
    const step = await largestStep(page, () =>
      page.getByRole("radio", { name: /v1/ }).click(),
    );
    expect(step).toBeLessThan(0.35);
    // It plays on, on the other version.
    await expect(page.getByRole("radio", { name: /v1/ })).toBeChecked();
    await expect(pause).toBeVisible();
    await pause.click();
  });

  await test.step("a comment on v1 stays on v1", async () => {
    await page.getByRole("radio", { name: /v1/ }).click();
    await page.getByLabel("Comment", { exact: true }).fill(onFirst);
    await page.getByRole("button", { name: "Comment", exact: true }).click();
    await expect(page.getByText(onFirst)).toBeVisible();
    await page.getByRole("radio", { name: /v2/ }).click();
    await expect(page.getByText(onFirst)).toBeHidden();
    // v2 has none, so the page says where the comment is.
    // That note is the only empty state.
    await expect(page.getByText("Quiet in here.")).toHaveCount(0);
    await expect(page.getByText("No comments yet.")).toHaveCount(0);
    await page.getByRole("button", { name: "1 comment on version 1" }).click();
    await expect(page.getByRole("radio", { name: /v1/ })).toBeChecked();
    await expect(page.getByText(onFirst)).toBeVisible();
    await page.getByRole("radio", { name: /v2/ }).click();

    // The latest version is picked after a reload, and the list follows it.
    await page.reload();
    await expect(page.getByRole("radio", { name: /v2/ })).toBeChecked();
    await expect(page.getByText(onFirst)).toBeHidden();
    await page.getByRole("radio", { name: /v1/ }).click();
    await expect(page.getByText(onFirst)).toBeVisible();
  });
});
